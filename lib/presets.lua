-- ASCII Grid format helper: 20 lines of 10 characters representing visible rows 21..40
-- '.' = Empty
-- 'X' = Garbage block
-- 'I','J','L','O','S','T','Z' = Specific mino types
local function parse_grid(ascii_str)
    local board = Board.new()
    local lines = {}
    for line in ascii_str:gmatch("[^\r\n]+") do
        -- Trim trailing whitespace or comments if any
        line = line:match("^%s*(.-)%s*$")
        if #line == 10 then
            table.insert(lines, line)
        end
    end

    -- We expect 20 rows corresponding to rows 21..40
    local start_row = 40 - #lines + 1
    for r_idx, line in ipairs(lines) do
        local target_row = start_row + r_idx - 1
        for col = 1, 10 do
            local char = line:sub(col, col)
            if char ~= "." then
                Board.set_cell(board, target_row, col, char)
            end
        end
    end
    return board
end

