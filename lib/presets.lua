function Presets.getByCategory(cat_id)
    local results = {}
    for _, item in ipairs(Presets.list) do
        if item.category == cat_id then
            table.insert(results, item)
        end
    end
    return results
end

function Presets.get(preset_id)
    for _, item in ipairs(Presets.list) do
        if item.id == preset_id then
            return item
        end
    end
    return nil
end

function Presets.build_board(preset)
    if not preset or not preset.ascii then
        return Board.new()
    end
    return parse_grid(preset.ascii)
end

return Presets
